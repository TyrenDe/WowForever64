namespace WowForever.C64.Core;

public static class FantasyCharset
{
    public static CharacterSet Default { get; } = Create();

    public static CharacterSet Create()
    {
        var bytes = new byte[CharacterSet.ByteCount];
        void Glyph(int code, params byte[] rows)
        {
            if (rows.Length != 8) throw new ArgumentException("Glyphs require eight rows.");
            rows.CopyTo(bytes, code * 8);
        }
        void Shape(TileId tile, params string[] rows)
        {
            if (rows.Length != 8 || rows.Any(row => row.Length != 8))
                throw new ArgumentException("Tile art must be 8 by 8.");
            Glyph((byte)tile, rows.Select(row => Convert.ToByte(row.Replace('.', '0').Replace('#', '1'), 2)).ToArray());
        }

        // Original six-pixel uppercase face. Slots match ASCII, not ROM screen codes.
        var font = new Dictionary<char, string>
        {
            [' ']="00000000000000", ['!']="18181818180018", ['\"']="36362400000000",
            ['#']="36367F367F3636", ['$']="183E603C067C18", ['%']="62660C18306646",
            ['&']="386C383B6E663B", ['\'']="18183000000000", ['(']="0C18303030180C",
