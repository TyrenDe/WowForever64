        Shape(TileId.TitleLeft, ".......#", "....#.##", "...#####", "######.#", "...#####", "....#.##", ".......#", "........");
        Shape(TileId.TitleRight, "#.......", "##.#....", "#####...", "#.######", "#####...", "##.#....", "#.......", "........");
        Shape(TileId.Diamond, "........", "...#....", "..###...", ".#####..", "..###...", "...#....", "........", "........");
        Shape(TileId.HollowDiamond, "........", "...#....", "..#.#...", ".#...#..", "..#.#...", "...#....", "........", "........");
        Shape(TileId.Sparkle, "...#....", "...#..#.", "...#.#..", "#######.", "..#.#...", ".#.#....", "#..#....", "........");
        Shape(TileId.Hourglass, ".######.", "..#..#..", "..#..#..", "...##...", "...##...", "..####..", "..####..", ".######.");
        Shape(TileId.Shield, ".######.", ".#....#.", ".#.#..#.", ".####.#.", ".#.#..#.", "..#..#..", "...##...", "........");
        Shape(TileId.Sword, "......##", ".....###", "....###.", "...###..", ".#.##...", "..##....", ".#.##...", "#.......");
        Shape(TileId.Skull, "..####..", ".######.", "##.##.##", "##.##.##", ".######.", "..#..#..", "..####..", "........");
        Shape(TileId.Flame, "...#....", "...##...", "..###...", ".#.###..", ".#####..", "..###...", ".#.#.#..", "##...##.");
        Shape(TileId.Live, "...##...", "..####..", ".######.", ".######.", "..####..", "...##...", "........", "........");
        Shape(TileId.Paused, "........", ".##..##.", ".##..##.", ".##..##.", ".##..##.", ".##..##.", "........", "........");
        Shape(TileId.Lost, "........", ".#....#.", "..#..#..", "...##...", "...##...", "..#..#..", ".#....#.", "........");
        for (var amount = 0; amount <= 8; amount++)
        {
            var fill = amount == 0 ? (byte)0 : (byte)(255 << (8 - amount));
            Glyph(96 + amount, 0, 255, 0, fill, fill, 0, 255, 0);
        }
        Glyph(105, 0, 15, 16, 16, 16, 16, 15, 0);
        Glyph(106, 0, 240, 8, 8, 8, 8, 240, 0);
        Glyph(107, 0, 102, 153, 153, 102, 0, 0, 0);
        Glyph(108, 24, 36, 66, 126, 36, 24, 36, 66);

        void Icon(TileId start, params string[] art)
        {
            if (art.Length != 16 || art.Any(row => row.Length != 16)) throw new ArgumentException("Icons must be 16 by 16.");
            for (var tileY = 0; tileY < 2; tileY++)
                for (var tileX = 0; tileX < 2; tileX++)
                    Glyph((byte)start + tileY * 2 + tileX, Enumerable.Range(0, 8)
                        .Select(row => Convert.ToByte(art[tileY * 8 + row].Substring(tileX * 8, 8).Replace('.', '0').Replace('#', '1'), 2)).ToArray());
        }
        Icon(TileId.CampTopLeft,
            ".......#........", ".......##.......", "......###.......", "......####......",
            ".....#####......", "...#.######.....", "...#########....", "..###########...",
            "..###.#######...", "...###.#####....", "....#######.....", ".....#####......",
            "..##...##...##..", "...####..####...", "..############..", "##............##");
        Icon(TileId.ShieldTopLeft,
            "..############..", ".#............#.", ".#.##########.#.", ".#.#........#.#.",
            ".#.#...##...#.#.", ".#.#...##...#.#.", ".#.#.######.#.#.", ".#.#...##...#.#.",
            ".#.#...##...#.#.", "..#.#......#.#..", "..#..#....#..#..", "...#..#..#..#...",
            "....#..##..#....", ".....#....#.....", "......#..#......", ".......##.......");
        Icon(TileId.SwordTopLeft,
            "............####", "...........#####", "..........###.##", ".........###.##.",
            "........###.##..", ".......###.##...", "......###.##....", ".....###.##.....",
            "..#.###.##......", "...###.##.......", "....####........", "...######.......",
            "..###..###......", ".###....#.......", "###.............", ".#..............");
        Icon(TileId.SkullTopLeft,
            ".....######.....", "...##########...", "..############..", ".##############.",
            ".###...##...###.", "####...##...####", "####...##...####", ".##############.",
            ".#####.##.#####.", "..####....####..", "...##########...", "....#.#..#.#....",
            "....########....", ".....######.....", "................", "................");
        Glyph(125, 0, 102, 255, 255, 126, 60, 24, 0);
        Glyph(126, 0, 16, 48, 127, 48, 16, 0, 0);
        Glyph(127, 28, 54, 48, 120, 48, 48, 126, 0);

        // The upper half contains inverse versions of every text/tile glyph.
        for (var code = 0; code < 128; code++)
            for (var row = 0; row < 8; row++) bytes[(code + 128) * 8 + row] = (byte)~bytes[code * 8 + row];
        Glyph((byte)TileId.DownArrow, 0, 0x18, 0x18, 0x18, 0x7E, 0x3C, 0x18, 0);
        return CharacterSet.FromBytes(bytes);
    }
}
