            ['8']="3C66663C66663C", ['9']="3C66663E060C38", [':']="00181800181800",
            [';']="00181800181830", ['<']="060C1830180C06", ['=']="00007E007E0000",
            ['>']="6030180C183060", ['?']="3C66060C180018", ['@']="3C666E6E60603C",
            ['A']="183C66667E6666", ['B']="7C36363C36367C", ['C']="3E66606060663E",
            ['D']="7C36363636367C", ['E']="7E32303830327E", ['F']="7E323038303078",
            ['G']="3E66606E66663E", ['H']="6666667E666666", ['I']="3C18181818183C",
            ['J']="1E0C0C0C6C6C38", ['K']="66363C383C3666", ['L']="7830303030327E",
            ['M']="63777F6B636363", ['N']="6676766E6E6666", ['O']="3C66666666663C",
            ['P']="7C36363C303078", ['Q']="3C6666666E3C0E", ['R']="7C36363C363666",
            ['S']="3E66603C06667C", ['T']="7E5A181818183C", ['U']="6666666666663C",
            ['V']="66666666663C18", ['W']="6363636B7F7763", ['X']="66663C183C6666",
            ['Y']="6666663C18183C", ['Z']="7E460C1830627E", ['[']="3C30303030303C",
            ['\\']="406030180C0602", [']']="3C0C0C0C0C0C3C", ['^']="183C7E18181818",
            ['_']="0000000000007E"
        };
        foreach (var (character, hex) in font)
        {
            var rows = Convert.FromHexString(hex).Concat(new byte[] { 0 }).ToArray();
            Glyph(character, rows);
        }

        Shape(TileId.FrameTopLeft, "...#####", "..#.....", ".#.#####", "#.#.....", "#.#.####", "#.#.#...", "#.#.#.##", "#.#.#.#.");
        Shape(TileId.FrameTop, "########", "........", "########", "........", "........", "........", "........", "........");
        Shape(TileId.FrameTopRight, "#####...", ".....#..", "#####.#.", ".....#.#", "####.#.#", "...#.#.#", "##.#.#.#", ".#.#.#.#");
        Shape(TileId.FrameLeft, "#.#.....", "#.#.....", "#.#.....", "#.#.#...", "#.#..#..", "#.#.#...", "#.#.....", "#.#.....");
        Shape(TileId.FrameRight, ".....#.#", ".....#.#", ".....#.#", "...#.#.#", "..#..#.#", "...#.#.#", ".....#.#", ".....#.#");
        Shape(TileId.FrameBottomLeft, "#.#.#.#.", "#.#.#.##", "#.#.#...", "#.#.####", "#.#.....", ".#.#####", "..#.....", "...#####");
        Shape(TileId.FrameBottom, "........", "........", "........", "........", "........", "########", "........", "########");
        Shape(TileId.FrameBottomRight, ".#.#.#.#", "##.#.#.#", "...#.#.#", "####.#.#", ".....#.#", "#####.#.", ".....#..", "#####...");
        Shape(TileId.PanelTopLeft, "...#####", "..#.....", ".#..####", "#..#....", "#.#.....", "#.#.....", "#.#.....", "#.#.....");
        Shape(TileId.PanelTop, "########", "........", "########", "........", "........", "........", "........", "........");
        Shape(TileId.PanelTopRight, "#####...", ".....#..", "####..#.", "....#..#", ".....#.#", ".....#.#", ".....#.#", ".....#.#");
        Shape(TileId.PanelLeft, "#.#.....", "#.#.....", "#.#.....", "#.#.....", "#.#.....", "#.#.....", "#.#.....", "#.#.....");
        Shape(TileId.PanelRight, ".....#.#", ".....#.#", ".....#.#", ".....#.#", ".....#.#", ".....#.#", ".....#.#", ".....#.#");
        Shape(TileId.PanelBottomLeft, "#.#.....", "#.#.....", "#.#.....", "#.#.....", "#..#....", ".#..####", "..#.....", "...#####");
        Shape(TileId.PanelBottom, "........", "........", "........", "........", "........", "########", "........", "########");
        Shape(TileId.PanelBottomRight, ".....#.#", ".....#.#", ".....#.#", ".....#.#", "....#..#", "####..#.", ".....#..", "#####...");
        Shape(TileId.SeparatorLeft, "#.#.....", "#.#.....", "#.######", "#.......", "#.######", "#.#.....", "#.#.....", "#.#.....");
        Shape(TileId.Separator, "........", "........", "########", "........", "########", "........", "........", "........");
